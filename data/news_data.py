import yfinance as yf
import pandas as pd


# ============================================================
# 設定
# ============================================================

STOCK_CODE = "6857.T"

STOCK_NAME = "アドバンテスト"


# ============================================================
# ニュース取得
# ============================================================

def get_news(stock_code=STOCK_CODE):
    """
    Yahoo Financeから銘柄関連ニュースを取得する

    Parameters
    ----------
    stock_code : str
        Yahoo Financeの銘柄コード

    Returns
    -------
    pandas.DataFrame
        ニュース一覧
    """

    try:

        # ----------------------------------------------------
        # Tickerオブジェクト作成
        # ----------------------------------------------------

        ticker = yf.Ticker(
            stock_code
        )


        # ----------------------------------------------------
        # ニュース取得
        # ----------------------------------------------------

        news = ticker.news


        # ----------------------------------------------------
        # ニュースがない場合
        # ----------------------------------------------------

        if news is None or len(news) == 0:

            return pd.DataFrame(
                columns=[
                    "title",
                    "publisher",
                    "published",
                    "url"
                ]
            )


        # ----------------------------------------------------
        # 整理用リスト
        # ----------------------------------------------------

        rows = []


        for item in news:

            try:

                # ------------------------------------------------
                # Yahoo Financeのバージョンによって
                # URL情報の構造が異なる場合があるため対応
                # ------------------------------------------------

                content = item.get(
                    "content",
                    {}
                )


                # ------------------------------------------------
                # タイトル
                # ------------------------------------------------

                title = (
                    content.get("title")
                    or item.get("title")
                    or ""
                )


                # ------------------------------------------------
                # 配信元
                # ------------------------------------------------

                provider = (
                    content.get("provider", {})
                )


                publisher = (
                    provider.get("displayName")
                    if isinstance(provider, dict)
                    else ""
                )


                # 古い形式への対応

                if not publisher:

                    publisher = (
                        item.get("publisher")
                        or ""
                    )


                # ------------------------------------------------
                # 公開日時
                # ------------------------------------------------

                pub_date = (
                    content.get(
                        "pubDate"
                    )
                    or item.get(
                        "providerPublishTime"
                    )
                )


                # ------------------------------------------------
                # URL
                # ------------------------------------------------

                canonical = (
                    content.get(
                        "canonicalUrl",
                        {}
                    )
                )


                if isinstance(
                    canonical,
                    dict
                ):

                    url = (
                        canonical.get(
                            "url"
                        )
                        or ""
                    )

                else:

                    url = ""


                # 古い形式への対応

                if not url:

                    link = item.get(
                        "link"
                    )

                    if link:

                        url = link


                # ------------------------------------------------
                # データ追加
                # ------------------------------------------------

                rows.append(
                    {
                        "title": title,
                        "publisher": publisher,
                        "published": pub_date,
                        "url": url
                    }
                )


            except Exception:

                # 1件のニュースに問題があっても
                # 他のニュース取得を継続
                continue


        # --------------------------------------------------------
        # DataFrame化
        # --------------------------------------------------------

        df = pd.DataFrame(
            rows
        )


        # --------------------------------------------------------
        # 空の場合
        # --------------------------------------------------------

        if df.empty:

            return pd.DataFrame(
                columns=[
                    "title",
                    "publisher",
                    "published",
                    "url"
                ]
            )


        # --------------------------------------------------------
        # 公開日時を整理
        # --------------------------------------------------------

        df["published"] = pd.to_datetime(
            df["published"],
            errors="coerce",
            utc=True
        )


        # --------------------------------------------------------
        # 最新ニュース順
        # --------------------------------------------------------

        df.sort_values(
            "published",
            ascending=False,
            inplace=True
        )


        # --------------------------------------------------------
        # インデックス整理
        # --------------------------------------------------------

        df.reset_index(
            drop=True,
            inplace=True
        )


        return df


    except Exception as e:

        raise RuntimeError(
            f"ニュース取得中にエラーが発生しました：{e}"
        ) from e


# ============================================================
# 最新ニュース取得
# ============================================================

def get_latest_news(
    stock_code=STOCK_CODE,
    limit=10
):
    """
    最新ニュースを指定件数取得する
    """

    news = get_news(
        stock_code
    )


    if news.empty:

        return news


    return news.head(
        limit
    ).copy()


# ============================================================
# ニュースタイトルだけ取得
# ============================================================

def get_news_titles(
    stock_code=STOCK_CODE,
    limit=10
):
    """
    AIの前処理などで使用するため、
    ニュースタイトルだけを取得する
    """

    news = get_latest_news(
        stock_code=stock_code,
        limit=limit
    )


    if news.empty:

        return []


    return news[
        "title"
    ].dropna().tolist()


# ============================================================
# ニュース件数
# ============================================================

def get_news_count(
    stock_code=STOCK_CODE
):
    """
    現在取得できるニュース件数を返す
    """

    news = get_news(
        stock_code
    )


    return len(news)
